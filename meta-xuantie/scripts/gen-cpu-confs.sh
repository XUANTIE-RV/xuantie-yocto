#!/bin/bash
# Generate CPU model distro/machine .conf files from cpu-isa-mapping.conf.
#
# Usage: bash scripts/gen-cpu-confs.sh [--toolchain DIR] [--clang-toolchain DIR]
#
#   --toolchain DIR        Xuantie GCC toolchain root directory (containing bin/)
#   --clang-toolchain DIR  Xuantie Clang toolchain root directory (containing bin/)
#
# Note: --toolchain / --clang-toolchain expect the toolchain ROOT directory
# (the one that contains bin/), not a binary file path. The script
# auto-corrects common mistakes (e.g. .../bin/<...>-gcc, .../bin/clang or
# .../bin) by stripping back to the root, but always pass the root form
# explicitly when possible.
#
# Inputs (read-only):
#   - recipes-bsp/hw-c9xx/files/fpga/data/cpu-isa-configs/cpu-isa-mapping.conf
#     CPU-to-ISA SoT. Refresh it explicitly via sync-cpu-isa-mapping.sh —
#     this script never writes back to it.
#
# This script:
#   1. Loads the CPU list and per-CPU ISA strings from cpu-isa-mapping.conf
#   2. Probes the GCC toolchain for supported -march= profile values (rva22u64 etc.)
#      and per-CPU -mtune values
#   3. Auto-detects flags from CPU names (rv32, softfloat, libxtstring)
#   4. Auto-generates -gnu variants for all C/R/xt series
#   5. Writes distro/machine .conf files
#
# Output:
#   - conf/distro/<model>.conf          (distro config)
#   - conf/machine/<model>-rv64-tcxt.conf or <model>-tcxt.conf  (empty machine)
#   - conf/distro/include/<profile>.inc (profile include, auto-created if missing)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
META_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
DISTRO_DIR="$META_DIR/conf/distro"
MACHINE_DIR="$META_DIR/conf/machine"
# Default: toolchain at repo root (standard xuantie-yocto layout)
DEFAULT_TC="$(cd "$META_DIR/.." && pwd)/xuantie-toolchain-gcc"

HEADER="# Auto-generated by gen-cpu-confs.sh — do not edit manually"

# --- Parse arguments ---
TOOLCHAIN_PATH=""
CLANG_TOOLCHAIN_PATH=""
while [ $# -gt 0 ]; do
    case "$1" in
        --toolchain)       TOOLCHAIN_PATH="$2"; shift 2 ;;
        --clang-toolchain) CLANG_TOOLCHAIN_PATH="$2"; shift 2 ;;
        *)                 echo "Usage: $0 [--toolchain DIR] [--clang-toolchain DIR]" >&2; exit 1 ;;
    esac
done

# --- Auto-correct toolchain path: strip trailing bin/<binary> back to root ---
# Users sometimes pass the GCC binary path (e.g. .../bin/riscv64-*-gcc) or the
# bin/ directory itself instead of the toolchain root, which would corrupt
# downstream "$TOOLCHAIN_PATH/bin/..." composition. Detect both shapes and
# fall back to the root before any GCC_BIN assignment.
if [ -n "$TOOLCHAIN_PATH" ]; then
    if [[ "$TOOLCHAIN_PATH" == */bin/*gcc ]] || [[ "$TOOLCHAIN_PATH" == */bin/*-gcc ]]; then
        TOOLCHAIN_PATH="$(dirname "$(dirname "$TOOLCHAIN_PATH")")"
        echo "INFO: Auto-corrected --toolchain to root: $TOOLCHAIN_PATH" >&2
    elif [[ "$TOOLCHAIN_PATH" == */bin ]]; then
        TOOLCHAIN_PATH="$(dirname "$TOOLCHAIN_PATH")"
        echo "INFO: Auto-corrected --toolchain to root: $TOOLCHAIN_PATH" >&2
    fi
fi

if [ -n "$CLANG_TOOLCHAIN_PATH" ]; then
    if [[ "$CLANG_TOOLCHAIN_PATH" == */bin/*clang* ]] || [[ "$CLANG_TOOLCHAIN_PATH" == */bin ]]; then
        CLANG_TOOLCHAIN_PATH="$(dirname "$(dirname "$CLANG_TOOLCHAIN_PATH")")"
        echo "INFO: Auto-corrected --clang-toolchain to root: $CLANG_TOOLCHAIN_PATH" >&2
    fi
fi

# --- Locate toolchain binaries ---
if [ -z "$TOOLCHAIN_PATH" ]; then
    TOOLCHAIN_PATH="$DEFAULT_TC"
fi
GCC_BIN="$TOOLCHAIN_PATH/bin/riscv64-unknown-linux-gnu-gcc"
GCC_READELF_BIN="$TOOLCHAIN_PATH/bin/riscv64-unknown-linux-gnu-readelf"
GCC_AVAILABLE=0
if [ -x "$GCC_BIN" ]; then
    GCC_AVAILABLE=1
    echo "GCC Toolchain: $GCC_BIN"
    echo "  $($GCC_BIN --version | head -1)"
    if [ ! -x "$GCC_READELF_BIN" ]; then
        echo "WARNING: readelf not found at $GCC_READELF_BIN; versioned march query will return empty" >&2
    fi
fi
export GCC_READELF_BIN

# Auto-detect Clang toolchain path if not specified
if [ -z "$CLANG_TOOLCHAIN_PATH" ]; then
    CLANG_TOOLCHAIN_PATH="$(cd "$META_DIR/.." && pwd)/xuantie-toolchain-clang"
fi
CLANG_AVAILABLE=0
if [ -n "$CLANG_TOOLCHAIN_PATH" ] && [ -f "$CLANG_TOOLCHAIN_PATH/include/llvm/TargetParser/RISCVTargetParserDef.inc" ]; then
    CLANG_AVAILABLE=1
    echo "Clang Toolchain: $CLANG_TOOLCHAIN_PATH"
    echo "  RISCVTargetParserDef.inc found"
fi

# Profile probing (rva*u64, rvb*u64) needs a GCC that accepts those -march=
# strings. XuanTie GCC is preferred; without it, scan $TOP_DIR/riscv-toolchain-gcc-*
# for an open-source GCC. Per-CPU XuanTie data is loaded from
# cpu-isa-mapping.conf in Step 1 (no toolchain probe).
OSGCC_BIN=""
TOP_DIR="$(cd "$META_DIR/.." && pwd)"
if [ $GCC_AVAILABLE -eq 0 ]; then
    if [ $CLANG_AVAILABLE -eq 0 ]; then
        echo "WARNING: neither XuanTie GCC nor XuanTie Clang found; degrading to open-source GCC." >&2
    else
        echo "WARNING: XuanTie GCC not found; scanning for open-source GCC to enable profile probing." >&2
    fi
    for d in "$TOP_DIR"/riscv-toolchain-gcc-glibc64 \
             "$TOP_DIR"/riscv-toolchain-gcc-muslc64 \
             "$TOP_DIR"/riscv-toolchain-gcc-uclibc-ng64 \
             "$TOP_DIR"/riscv-toolchain-gcc-glibc32 \
             "$TOP_DIR"/riscv-toolchain-gcc-muslc32 \
             "$TOP_DIR"/riscv-toolchain-gcc-uclibc-ng32; do
        cand=$(find "$d/bin" -maxdepth 1 -name 'riscv*-gcc' -type f 2>/dev/null | head -1)
        if [ -n "$cand" ] && [ -x "$cand" ]; then
            OSGCC_BIN="$cand"
            echo "  Open-source GCC: $OSGCC_BIN"
            echo "    $($OSGCC_BIN --version | head -1)"
            break
        fi
    done
    if [ -z "$OSGCC_BIN" ]; then
        if [ $CLANG_AVAILABLE -eq 0 ]; then
            echo "ERROR: no open-source GCC found under $TOP_DIR/riscv-toolchain-gcc-*" >&2
            echo "Specify --toolchain PATH (XuanTie) or install an open-source riscv-toolchain-gcc-* sibling." >&2
            exit 1
        else
            echo "WARNING: no open-source GCC found; -march= profile probing will be skipped (Clang-only run)." >&2
        fi
    fi
fi

# Profile probing binary: prefer XuanTie GCC, fall back to open-source GCC.
# May be empty when XuanTie GCC absent and no open-source GCC found (Clang-only
# scenario); Step 1b checks before invoking.
PROFILE_PROBE_GCC="${GCC_BIN}"
if [ $GCC_AVAILABLE -eq 0 ]; then
    PROFILE_PROBE_GCC="$OSGCC_BIN"
fi

echo "META_DIR: $META_DIR"

# 创建必需的目录
directories=(
    "conf/distro"
    "conf/distro/include"
    "conf/machine"
)

for dir in "${directories[@]}"; do
    full_path="$META_DIR/$dir"
    if [ ! -d "$full_path" ]; then
        echo "创建目录: $full_path"
        mkdir -p "$full_path"
    else
        echo "目录已存在: $full_path"
    fi
done

# --- Snapshot previous ledger for stale-file cleanup at end of run ---
# .gitignore.distro lists every file this script produces. By snapshotting it
# before regeneration and diffing against the new one, we can identify files
# we previously generated but no longer should — e.g. when a CPU disappears
# from the toolchain — and delete them.
PREV_GITIGNORE_SNAPSHOT="$META_DIR/.gitignore.distro.bak"
if [ -f "$META_DIR/.gitignore.distro" ]; then
    cp "$META_DIR/.gitignore.distro" "$PREV_GITIGNORE_SNAPSHOT"
else
    rm -f "$PREV_GITIGNORE_SNAPSHOT"
fi

# --- Helper functions ---
# Shared with audit-cpu-mapping.sh (planned). See lib/cpu-confs-lib.sh for:
#   query_gcc_march, query_gcc_mtune, query_clang_march, query_clang_cpu_list,
#   query_march, strip_arch_versions, normalize_march, detect_gnu_blocklist,
#   pick_probe_march_from_mapping, detect_and_save_blocklist, load_union_blocklist
source "$SCRIPT_DIR/lib/cpu-confs-lib.sh"

# Load open-source toolchain blocklist union (populated by toolchain-init.sh).
# Used by normalize_march in 'gnu_strict' mode for -gnu.conf to drop
# extensions that open-source GCC/Clang don't accept. TOP_DIR was defined
# above near the OSGCC_BIN scan; reused here.
GNU_BLOCKLIST=$(load_union_blocklist \
    "$TOP_DIR"/riscv-toolchain-gcc-glibc64 \
    "$TOP_DIR"/riscv-toolchain-gcc-glibc32 \
    "$TOP_DIR"/riscv-toolchain-gcc-muslc64 \
    "$TOP_DIR"/riscv-toolchain-gcc-muslc32 \
    "$TOP_DIR"/riscv-toolchain-gcc-uclibc-ng64 \
    "$TOP_DIR"/riscv-toolchain-gcc-uclibc-ng32 \
    "$TOP_DIR"/riscv-toolchain-clang-glibc64 \
    "$TOP_DIR"/riscv-toolchain-clang-glibc32 \
    "$TOP_DIR"/riscv-toolchain-clang-muslc64 \
    "$TOP_DIR"/riscv-toolchain-clang-muslc32)
export GNU_BLOCKLIST
if [ -n "$GNU_BLOCKLIST" ]; then
    echo "GNU blocklist (union from open-source toolchain dirs): $GNU_BLOCKLIST"
else
    echo "GNU blocklist: empty (no open-source toolchain .gnu-blocklist found; -gnu.conf will not strip vendor-only extensions)"
fi

# --- Step 1: Load CPU list and per-CPU ISA from cpu-isa-mapping.conf ---
# cpu-isa-mapping.conf is the single source of truth — both the CPU coverage
# and each model's compact ISA string come from it. Refresh it explicitly via
# meta-xuantie/scripts/sync-cpu-isa-mapping.sh; this script never writes back.
MAPPING_FILE="$META_DIR/recipes-bsp/hw-c9xx/files/fpga/data/cpu-isa-configs/cpu-isa-mapping.conf"

if [ ! -f "$MAPPING_FILE" ]; then
    echo "ERROR: cpu-isa-mapping.conf not found at $MAPPING_FILE" >&2
    echo "       Generate it first:" >&2
    echo "         bash meta-xuantie/scripts/sync-cpu-isa-mapping.sh --yes" >&2
    exit 1
fi

# Source the mapping (it's a bash associative-array file) so we can read it
# straight into CPU_ISA_MAP rather than grep+sed each entry.
declare -A default_isa
# shellcheck disable=SC1090
. "$MAPPING_FILE"

# Source all additional .conf files in the same directory (e.g. xt-c9301.conf)
# so that CPU definitions not covered by the auto-generated mapping are included.
MAPPING_DIR="$(dirname "$MAPPING_FILE")"
for extra_conf in "$MAPPING_DIR"/*.conf; do
    [ "$extra_conf" = "$MAPPING_FILE" ] && continue
    [ -f "$extra_conf" ] || continue
    # shellcheck disable=SC1090
    . "$extra_conf"
done

declare -A CPU_ISA_MAP
for cpu in "${!default_isa[@]}"; do
    CPU_ISA_MAP["$cpu"]="${default_isa[$cpu]}"
done

FILTERED_CPUS=$(printf '%s\n' "${!CPU_ISA_MAP[@]}" | sort)
if [ -z "$FILTERED_CPUS" ]; then
    echo "ERROR: cpu-isa-mapping.conf is empty — run sync-cpu-isa-mapping.sh to populate it." >&2
    exit 1
fi
echo "Loaded $(echo "$FILTERED_CPUS" | wc -l) CPU models from cpu-isa-mapping.conf"

# Detect softfloat CPUs from each CPU's base ISA (no fresh toolchain probe).
declare -A SOFTFLOAT_CPUS
echo "Detecting softfloat CPUs..."
for cpu in $FILTERED_CPUS; do
    cpu_arch="${CPU_ISA_MAP[$cpu]}"
    
    # Check base ISA for f/d/g extensions (e.g., rv64imafdc -> has f/d, rv64imac -> softfloat)
    # g implicitly includes f and d
    # For Clang-style arch (rv64i2p1_f2p2_d2p2_...), also check extensions
    if [[ -n "$cpu_arch" ]]; then
        base_isa=$(echo "$cpu_arch" | cut -d'_' -f1)  # e.g., rv64imac or rv64i2p1
        # Extract the part after rv64/rv32 (e.g., imac, imafdc, gc, i2p1)
        isa_suffix=$(echo "$base_isa" | sed 's/^rv[0-9]*//')
        has_float=false
        if [[ "$isa_suffix" == *f* ]] || [[ "$isa_suffix" == *d* ]] || [[ "$isa_suffix" == *g* ]]; then
            has_float=true
        fi
        # Also check if f/d/g exist as separate extensions (Clang-style: f2p2, d2p2, g1p0)
        if [ "$has_float" = false ]; then
            for ext in $(echo "$cpu_arch" | tr '_' '\n' | tail -n +2); do
                ext_name=$(echo "$ext" | sed 's/[0-9]*p[0-9]*$//')
                if [[ "$ext_name" == "f" ]] || [[ "$ext_name" == "d" ]] || [[ "$ext_name" == "g" ]]; then
                    has_float=true
                    break
                fi
            done
        fi
        if [ "$has_float" = false ]; then
            SOFTFLOAT_CPUS["$cpu"]=1
            echo "  softfloat: $cpu (base: $base_isa)"
        fi
    fi
done

echo "Loaded $(echo "$FILTERED_CPUS" | wc -l) CPU models ($(echo ${!SOFTFLOAT_CPUS[@]} | wc -w) softfloat)"

# --- Step 1a: Refresh GNU blocklist using union of ELF-derived marches ---
# The cached .gnu-blocklist files are produced by toolchain-init.sh using a
# probe march drawn from cpu-isa-mapping.conf, which is unversioned and may
# omit extensions reported by readelf (e.g. smrnmi, zvqdotq). To make sure the
# blocklist covers every extension that may appear in a per-CPU -gnu conf, we
# build a union march directly from the toolchain's ELF output for every CPU
# model, then re-probe each open-source toolchain dir and merge the results
# into GNU_BLOCKLIST.
declare -A _UNION_RV64_EXTS=()
declare -A _UNION_RV32_EXTS=()
_UNION_RV64_BASE=""
_UNION_RV32_BASE=""
for _cpu in $FILTERED_CPUS; do
    _m=""
    if [ "$GCC_AVAILABLE" -eq 1 ]; then
        _m=$(query_gcc_march "$_cpu") || true
    fi
    if [ -z "$_m" ] && [ "$CLANG_AVAILABLE" -eq 1 ]; then
        _m=$(query_clang_march "$_cpu") || true
    fi
    [ -z "$_m" ] && continue
    _base=$(echo "$_m" | cut -d_ -f1)
    if [[ "$_base" == rv32* ]]; then
        [ -z "$_UNION_RV32_BASE" ] && _UNION_RV32_BASE="$_base"
        for _tok in $(echo "$_m" | tr '_' '\n' | tail -n +2); do
            _UNION_RV32_EXTS[$_tok]=1
        done
    else
        [ -z "$_UNION_RV64_BASE" ] && _UNION_RV64_BASE="$_base"
        for _tok in $(echo "$_m" | tr '_' '\n' | tail -n +2); do
            _UNION_RV64_EXTS[$_tok]=1
        done
    fi
done

_build_union_probe() {
    local base="$1"; shift
    [ -z "$base" ] && return 0
    local toks="$*"
    if [ -n "$toks" ]; then
        echo "${base}_$(echo "$toks" | tr ' ' '\n' | sort | tr '\n' '_' | sed 's/_$//')"
    else
        echo "$base"
    fi
}
UNION_PROBE_RV64=$(_build_union_probe "$_UNION_RV64_BASE" "${!_UNION_RV64_EXTS[@]}")
UNION_PROBE_RV32=$(_build_union_probe "$_UNION_RV32_BASE" "${!_UNION_RV32_EXTS[@]}")
[ -n "$UNION_PROBE_RV64" ] && echo "Union RV64 probe march: $UNION_PROBE_RV64"
[ -n "$UNION_PROBE_RV32" ] && echo "Union RV32 probe march: $UNION_PROBE_RV32"

_dynamic_bl=""
for _d in "$TOP_DIR"/riscv-toolchain-gcc-glibc64 \
          "$TOP_DIR"/riscv-toolchain-gcc-muslc64 \
          "$TOP_DIR"/riscv-toolchain-gcc-uclibc-ng64; do
    [ -d "$_d" ] || continue
    [ -n "$UNION_PROBE_RV64" ] || continue
    _bl=$(detect_gnu_blocklist "$_d" "" "$UNION_PROBE_RV64" "rv64") || true
    _dynamic_bl="$_dynamic_bl $_bl"
done
for _d in "$TOP_DIR"/riscv-toolchain-clang-glibc64 \
          "$TOP_DIR"/riscv-toolchain-clang-muslc64; do
    [ -d "$_d" ] || continue
    [ -n "$UNION_PROBE_RV64" ] || continue
    _bl=$(detect_gnu_blocklist "" "$_d" "$UNION_PROBE_RV64" "rv64") || true
    _dynamic_bl="$_dynamic_bl $_bl"
done
for _d in "$TOP_DIR"/riscv-toolchain-gcc-glibc32 \
          "$TOP_DIR"/riscv-toolchain-gcc-muslc32 \
          "$TOP_DIR"/riscv-toolchain-gcc-uclibc-ng32; do
    [ -d "$_d" ] || continue
    [ -n "$UNION_PROBE_RV32" ] || continue
    _bl=$(detect_gnu_blocklist "$_d" "" "$UNION_PROBE_RV32" "rv32") || true
    _dynamic_bl="$_dynamic_bl $_bl"
done
for _d in "$TOP_DIR"/riscv-toolchain-clang-glibc32 \
          "$TOP_DIR"/riscv-toolchain-clang-muslc32; do
    [ -d "$_d" ] || continue
    [ -n "$UNION_PROBE_RV32" ] || continue
    _bl=$(detect_gnu_blocklist "" "$_d" "$UNION_PROBE_RV32" "rv32") || true
    _dynamic_bl="$_dynamic_bl $_bl"
done

if [ -n "$(echo "$_dynamic_bl" | tr -d ' ')" ]; then
    GNU_BLOCKLIST=$(echo "$GNU_BLOCKLIST $_dynamic_bl" \
        | tr ' ' '\n' | { grep -v '^$' || true; } \
        | sort -u | tr '\n' ' ' | sed 's/ $//')
    export GNU_BLOCKLIST
    echo "GNU blocklist (refreshed via ELF-union probe): $GNU_BLOCKLIST"
fi

# --- Step 1b: Query toolchain for supported march profiles ---
# Known RISC-V profiles to test against the toolchain
KNOWN_PROFILES="rva20u32 rva20u64 rva22u32 rva22u64 rva23u32 rva23u64 rvb21u64 rvb22u64 rvb23u64"

SUPPORTED_PROFILES=""
# PROFILE_PROBE_GCC may be empty in Clang-only runs (no XuanTie GCC, no open-
# source GCC found). Skip probing rather than invoke an empty command.
if [ -n "$PROFILE_PROBE_GCC" ] && [ -x "$PROFILE_PROBE_GCC" ]; then
    for profile in $KNOWN_PROFILES; do
        if "$PROFILE_PROBE_GCC" -march="$profile" -mabi=lp64d -print-multi-directory >/dev/null 2>&1; then
            SUPPORTED_PROFILES="$SUPPORTED_PROFILES $profile"
        fi
    done
fi
SUPPORTED_PROFILES=$(echo "$SUPPORTED_PROFILES" | xargs | tr ' ' '\n' | sort -u)

if [ -n "$SUPPORTED_PROFILES" ]; then
    profile_count=$(echo "$SUPPORTED_PROFILES" | wc -l)
    echo "Discovered $profile_count march profiles from toolchain: $(echo $SUPPORTED_PROFILES | tr '\n' ' ')"
fi

# --- Step 1c: Define standard ISA strings for arch mode ---
# Standard ISA strings (supported by both xuantie and riscv-gnu toolchains)
# With hardware FPU (f/d/g extensions): rv32gc, rv64gc, rv64gcv, rv32gcv
# Softfloat (no f/d/g): rv32imac, rv64imac
STANDARD_ISAS="rv32gc rv64gc rv32gcv rv64gcv rv32imac rv64imac"
# ISA strings with XuanTie extensions (xuantie toolchain only)
XUANTIE_ISAS="rv32gc_zfh_xtheadc rv64gc_zfh_xtheadc"
# All arch mode ISAs (for xuantie toolchain)
ALL_ARCH_ISAS="$STANDARD_ISAS $XUANTIE_ISAS"

echo "Arch mode ISA strings: $(echo $ALL_ARCH_ISAS | tr ' ' ', ')"

# Internal model flags (auto-detected, no user overrides)
declare -A OVERRIDE_FLAGS

# --- Step 3: Build model list ---
# All models are discovered from toolchain; no user overrides needed.
ALL_MODELS="$FILTERED_CPUS"

# --- Step 3b: Auto-register discovered profiles ---
# For each toolchain-supported profile, register as 'isa_auto' model.
# Also auto-create a .inc file if one doesn't exist.
INC_DIR="$META_DIR/conf/distro/include"
generated_inc=0

for profile in $SUPPORTED_PROFILES; do
    # Register as 'isa_auto' model (auto-detected arch mode)
    OVERRIDE_FLAGS["$profile"]="isa_auto"
    ALL_MODELS=$(printf '%s\n%s' "$ALL_MODELS" "$profile")

    # Auto-create .inc file if missing
    inc_file="$INC_DIR/${profile}.inc"
    if [ ! -f "$inc_file" ]; then
        arch="rv64"
        if [[ "$profile" == *u32 ]] || [[ "$profile" == *s32 ]]; then
            arch="rv32"
        fi
        {
            echo "# $profile ISA profile (auto-generated)"
            echo "require conf/distro/include/${arch}.inc"
            echo "XUANTIE_MARCH = \"$profile\""
        } > "$inc_file"
        generated_inc=$((generated_inc + 1))
        echo "  Created $inc_file"
    fi
done

# --- Step 3c: Register standard ISA strings for arch mode ---
# These are the core arch mode distros supported by both toolchains.
# Standard ISAs: rv32gc rv64gc rv32imac rv64imac rv64imafdcv
# XuanTie ISAs: rv32gc_zfh_xtheadc rv64gc_zfh_xtheadc (xuantie only)
# ISA strings are auto-recognized by name pattern (rv64*/rv32*/rva*/rvb*),
# so we only need to register them, not set 'march' flag.
for isa in $ALL_ARCH_ISAS; do
    # Register as 'isa_auto' model (auto-detected arch mode)
    OVERRIDE_FLAGS["$isa"]="isa_auto"
    ALL_MODELS=$(printf '%s\n%s' "$ALL_MODELS" "$isa")

    # Auto-create .inc file if missing
    inc_file="$INC_DIR/${isa}.inc"
    if [ ! -f "$inc_file" ]; then
        arch="rv64"
        [[ "$isa" == rv32* ]] && arch="rv32"
        {
            echo "# $isa ISA string (auto-generated)"
            echo "require conf/distro/include/${arch}.inc"
            echo "XUANTIE_MARCH = \"$isa\""
        } > "$inc_file"
        generated_inc=$((generated_inc + 1))
        echo "  Created $inc_file"
    fi
done

ALL_MODELS=$(echo "$ALL_MODELS" | sort -u)

# --- Step 4: Generate confs ---
generated_distro=0
generated_machine=0
skipped=0
gcc_unsupported=0
declare -A GCC_UNSUPPORTED_MODELS=()

for model in $ALL_MODELS; do
    # Get override flags for this model (if any)
    user_flags="${OVERRIDE_FLAGS[$model]:-}"

    # Check skip flag
    if echo " $user_flags " | grep -q ' skip '; then
        skipped=$((skipped + 1))
        continue
    fi

    # Auto-detect flags from name
    is_rv32=false
    has_cp=false

    # rv32: name ends with -rv32
    if [[ "$model" == *-rv32 ]]; then
        is_rv32=true
    fi

    # cp: name contains -cp but NOT -cp-xt
    if [[ "$model" == *-cp* ]] && [[ "$model" != *-cp-xt* ]]; then
        has_cp=true
    fi

    # Parse user flags (override/supplement auto-detection)
    is_softfloat=false
    has_libxtstring=false
    is_march=false
    isa_profile=""
    mcpu_override=""
    is_isa_auto=false
    for flag in $user_flags; do
        case "$flag" in
            softfloat)     is_softfloat=true ;;
            libxtstring)   has_libxtstring=true ;;
            march)         is_march=true ;;
            isa_auto)      is_isa_auto=true ;; # auto-detected arch mode
            isa=*)         isa_profile="${flag#isa=}" ;;
            mcpu=*)        mcpu_override="${flag#mcpu=}" ;;
            variants=*)    ;; # handled in variant generation loop below
            skip)          ;; # already handled above
            *)             echo "WARNING: unknown flag '$flag' for model '$model'" >&2 ;;
        esac
    done

    # Auto-detect softfloat from toolchain detection results
    if [ -n "${SOFTFLOAT_CPUS[$model]:-}" ]; then
        is_softfloat=true
    fi

    # Auto-detect softfloat from ISA string (no 'f' or 'd' extension = softfloat)
    # Examples: rv32imac, rv64imac are softfloat; rv32gc, rv64gc have hardware FPU
    if [[ "$model" == rv32* ]] || [[ "$model" == rv64* ]]; then
        if [[ "$model" != *f* ]] && [[ "$model" != *d* ]] && [[ "$model" != *g* ]]; then
            is_softfloat=true
        fi
    fi

    # Auto-detect libxtstring for C930v/C950 series (exclude -gnu/-wo-xthead variants)
    # C930: only vector variants (model contains 'v' after c930); C950: all sub-models
    if [[ "$model" == *c930*v* || "$model" == *c950* ]] && [[ "$model" != *-gnu ]] && [[ "$model" != *-wo-xthead ]]; then
        has_libxtstring=true
    fi

    # Auto-detect arch mode from ISA string pattern (rv64*/rv32*/rva*/rvb*)
    if ! $is_march && ! $is_isa_auto; then
        if [[ "$model" == rv64* ]] || [[ "$model" == rv32* ]] || [[ "$model" == rva* ]] || [[ "$model" == rvb* ]]; then
            is_isa_auto=true
        fi
    fi

    # --- Generate distro conf ---
    distro_file="$DISTRO_DIR/${model}.conf"
    if $is_march || $is_isa_auto; then
        if [[ "$model" == rv64* ]] || [[ "$model" == rv32* ]]; then
            # Standard ISA string (rv64*/rv32*): ABI auto-detected by xuantie-passthrough.inc
            {
                echo "$HEADER"
                echo "require conf/distro/include/xuantie-passthrough.inc"
                echo "MACHINE = \"${model}-tcxt\""
                if $has_libxtstring; then
                    echo "LD_LIBXTSTRING = \"-lxtstring\""
                fi
            } > "$distro_file"
            generated_distro=$((generated_distro + 1))

            : > "$MACHINE_DIR/${model}-tcxt.conf"
            generated_machine=$((generated_machine + 1))
        else
            # ISA profile name (e.g., rva23u64): use its own .inc file directly
            {
                echo "$HEADER"
                echo "require conf/distro/include/${model}.inc"
                echo "MACHINE = \"${model}-tcxt\""
                if $has_libxtstring; then
                    echo "LD_LIBXTSTRING = \"-lxtstring\""
                fi
            } > "$distro_file"
            generated_distro=$((generated_distro + 1))

            : > "$MACHINE_DIR/${model}-tcxt.conf"
            generated_machine=$((generated_machine + 1))
        fi

        # march/isa_auto models are fully handled above; skip the common distro/machine generation below
        continue
    elif [ -n "$isa_profile" ]; then
        # ISA profile model: explicit includes
        # Machine file naming: same as standard CPU models
        if [[ "$model" == *-rv32 ]]; then
            machine_name="${model}-tcxt"
            base_arch="rv32"
        else
            machine_name="${model}-rv64-tcxt"
            base_arch="rv64"
        fi
        {
            echo "$HEADER"
            echo "require conf/distro/include/${base_arch}.inc"
            echo "require conf/distro/include/${isa_profile}.inc"
            echo "require conf/distro/include/mcpu.inc"
            echo ""
            if [ -n "$mcpu_override" ]; then
                echo "XUANTIE_MCPU = \"${mcpu_override}\""
            else
                echo "XUANTIE_MCPU = \"${model}\""
            fi
            echo "MACHINE = \"${machine_name}\""
            if $has_libxtstring; then
                echo ""
                echo "LD_LIBXTSTRING = \"-lxtstring\""
            fi
        } > "$distro_file"
    else
        # Standard model: use passthrough.inc
        # Check if toolchain supports this CPU
        toolchain_march=$(query_gcc_march "$model" 2>/dev/null || true)
        use_march_mode=false
        isa_string=""
        abi_string=""
        if [ -z "$toolchain_march" ] && [ -n "${CPU_ISA_MAP[$model]:-}" ]; then
            # Toolchain doesn't support this CPU, use march mode with ISA from mapping
            use_march_mode=true
            isa_string=$(normalize_march "${CPU_ISA_MAP[$model]}" "gnu_strict")
            # Derive ABI from ISA string
            if [[ "$isa_string" == *d* ]] || [[ "$isa_string" == *g* ]]; then
                if $is_rv32; then
                    abi_string="ilp32d"
                else
                    abi_string="lp64d"
                fi
            elif [[ "$isa_string" == *f* ]]; then
                if $is_rv32; then
                    abi_string="ilp32f"
                else
                    abi_string="lp64f"
                fi
            else
                if $is_rv32; then
                    abi_string="ilp32"
                else
                    abi_string="lp64"
                fi
            fi
        fi

        # A march-mode conf whose ISA the external GCC rejects is a build-time
        # landmine: libgcc-external pins TOOLCHAIN=gcc even under clang distros,
        # and the rejected -march comes back as a bogus sysroot that kills parsing.
        # Emit no conf at all so no consumer (LIT auto-discovery, manual DISTRO=)
        # can pick it up.
        if $use_march_mode; then
            if unsupported_exts=$(gcc_rejects_march "$isa_string" "$abi_string"); then
                echo "WARNING: Skip $model: GCC rejects -march (unsupported extension(s): ${unsupported_exts:-unknown})" >&2
                rm -f "$distro_file"
                GCC_UNSUPPORTED_MODELS[$model]=1
                gcc_unsupported=$((gcc_unsupported + 1))
                continue
            fi
        fi

        # Machine file naming
        if [[ "$model" == *-rv32 ]] || [[ "$model" == *-rv64 ]]; then
            machine_name="${model}-tcxt"
        else
            machine_name="${model}-rv64-tcxt"
        fi
        {
            echo "$HEADER"
            echo "require conf/distro/include/xuantie-passthrough.inc"
            if $use_march_mode; then
                echo "XUANTIE_USE_MARCH_MODE = \"1\""
                echo "XUANTIE_MARCH = \"${isa_string}\""
                echo "XUANTIE_MABI = \"${abi_string}\""
            fi
            echo "MACHINE = \"${machine_name}\""
            if $is_softfloat; then
                echo 'XUANTIE_SOFTFLOAT = "1"'
            fi

            if $has_libxtstring; then
                echo "LD_LIBXTSTRING = \"-lxtstring\""
            fi
        } > "$distro_file"
    fi
    generated_distro=$((generated_distro + 1))

    # --- Generate machine conf (empty) ---
    # Machine file naming rules:
    # - arch/profile models (rv32*/rv64*/rva*/rvb*): <model>-tcxt.conf
    # - CPU models with -rv32/-rv64 suffix (c907-rv32, c907-rv64): <model>-tcxt.conf
    # - CPU models without rv suffix (c907, c906, xt-*, etc.): <model>-rv64-tcxt.conf
    if [[ "$model" == rv32* ]] || [[ "$model" == rv64* ]] || [[ "$model" == rva* ]] || [[ "$model" == rvb* ]] || [[ "$model" == *-rv32 ]] || [[ "$model" == *-rv64 ]]; then
        machine_file="$MACHINE_DIR/${model}-tcxt.conf"
    else
        machine_file="$MACHINE_DIR/${model}-rv64-tcxt.conf"
    fi
    : > "$machine_file"
    generated_machine=$((generated_machine + 1))
done

echo ""
echo "Generated: $generated_distro distro, $generated_machine machine, $generated_inc profile inc (skipped $skipped, gcc-unsupported $gcc_unsupported)"

# --- Step 4b: Generate variant configs (-gnu only) ---
# Auto-generate -gnu variants for all C/R/xt series CPU models (not ISA strings or profiles).
# XUANTIE_NATIVE_MARCH and MTUNE are auto-detected from the toolchain.
var_distro=0
var_machine=0

for model in $ALL_MODELS; do
    user_flags="${OVERRIDE_FLAGS[$model]:-}"

    # Skip if model has skip flag
    if echo " $user_flags " | grep -q ' skip '; then
        continue
    fi

    # Skip ISA strings (rv64*/rv32*/rva*/rvb*) and profiles - they don't get variants
    if [[ "$model" == rv64* ]] || [[ "$model" == rv32* ]] || [[ "$model" == rva* ]] || [[ "$model" == rvb* ]]; then
        continue
    fi

    # Auto-detect arch
    is_rv32=false
    [[ "$model" == *-rv32 ]] && is_rv32=true
    arch_inc="rv64"
    if $is_rv32; then arch_inc="rv32"; fi

    # ISA string is queried directly from the toolchain so the distro conf
    # carries the full versioned ELF form (e.g. rv64i2p1_m2p0_..._zicfilp1p0)
    # required by Clang for experimental extensions and harmlessly accepted
    # by GCC. cpu-isa-mapping.conf is no longer consulted here — it remains
    # the unversioned SoT for the kernel side.
    raw_march=$(query_gcc_march "$model")
    if [ -z "$raw_march" ]; then
        raw_march=$(query_clang_march "$model") || true
    fi
    mtune=$(query_gcc_mtune "$model")

    if [ -z "$raw_march" ]; then
        echo "WARNING: Skip -gnu variant for $model: no toolchain march available" >&2
        continue
    fi

    # Generate -gnu variant (open-source toolchain)
    # Uses -march (derived from CPU, stripping xthead) -mabi (auto-derived)
    # No -mtune specified — compiler uses generic scheduling model by default
    distro_name="${model}-gnu"
    distro_file="$DISTRO_DIR/${distro_name}.conf"
    # 'gnu_strict' consumes GNU_BLOCKLIST (env var) populated above from
    # per-toolchain .gnu-blocklist files written by toolchain-init.sh.
    gnu_march=$(normalize_march "$raw_march" "gnu_strict")
    gnu_mabi=$(derive_mabi "$gnu_march" "$arch_inc")


    {
        echo "$HEADER"
        echo "require conf/distro/include/${arch_inc}.inc"
        echo ""
        echo 'XUANTIE_TUNE_CCARGS_USE_MCPU = "NO"'
        echo "XUANTIE_TUNE_CCARGS_GENERIC = \"-march=${gnu_march} -mabi=${gnu_mabi}\""
        echo "XUANTIE_TUNE_CCARGS = \"-march=${gnu_march} -mabi=${gnu_mabi}\""
        # Clang treats some standard ISA extensions (zabha, zicfilp, zicfiss,
        # zicclsm, etc.) as experimental in v18 and rejects the -march string
        # without -menable-experimental-extensions. Re-assert the flag here so
        # the per-CPU -gnu conf is self-contained when TOOLCHAIN=clang; the
        # :toolchain-clang override is added by xuantie-base.inc only when
        # TOOLCHAIN=clang, so GCC builds are unaffected. (Mirrors the global
        # declaration in xuantie-clang.inc; harmless if it appears twice.)
        echo 'XUANTIE_TUNE_CCARGS:append:toolchain-clang = " -menable-experimental-extensions"'
        echo 'XUANTIE_TUNE_CCARGS_GENERIC:append:toolchain-clang = " -menable-experimental-extensions"'
        echo "XUANTIE_MABI = \"${gnu_mabi}\""
        echo 'MACHINE_FEATURES += "toolchain-multilib toolchain-gnu"'
        echo ""
        echo "XUANTIE_NATIVE_MARCH = \"${gnu_march}\""
        echo ""
        # Machine naming: CPU models with -rv32/-rv64 suffix use <distro_name>-tcxt, others use <distro_name>-rv64-tcxt
        if [[ "$model" == *-rv32 ]] || [[ "$model" == *-rv64 ]]; then
            echo "MACHINE = \"${distro_name}-tcxt\""
        else
            echo "MACHINE = \"${distro_name}-rv64-tcxt\""
        fi
    } > "$distro_file"
    var_distro=$((var_distro + 1))
    # Machine conf
    if [[ "$model" == *-rv32 ]] || [[ "$model" == *-rv64 ]]; then
        : > "$MACHINE_DIR/${distro_name}-tcxt.conf"
    else
        : > "$MACHINE_DIR/${distro_name}-rv64-tcxt.conf"
    fi
    var_machine=$((var_machine + 1))

    # Generate -wo-xthead variant (xuantie toolchain without xthead extensions)
    # Only generate if the original march contains xthead extensions
    # Uses -march (derived from CPU, stripping xthead) -mabi (auto-derived) -mtune (CPU model)
    if [[ "$raw_march" == *xthead* ]]; then
        wo_distro_name="${model}-wo-xthead"
        wo_distro_file="$DISTRO_DIR/${wo_distro_name}.conf"
        wo_march=$(normalize_march "$raw_march" "xthead")
        wo_mabi=$(derive_mabi "$wo_march" "$arch_inc")
        # Machine naming: same suffix convention as the -gnu variant; self-references
        # the dedicated <distro>-tcxt machine file created just below.
        if [[ "$model" == *-rv32 ]] || [[ "$model" == *-rv64 ]]; then
            wo_machine="${wo_distro_name}-tcxt"
        else
            wo_machine="${wo_distro_name}-rv64-tcxt"
        fi

        {
            echo "$HEADER"
            echo "require conf/distro/include/${arch_inc}.inc"
            echo ""
            echo 'XUANTIE_TUNE_CCARGS_USE_MCPU = "NO"'
            echo "XUANTIE_TUNE_CCARGS = \"-march=${wo_march} -mabi=${wo_mabi} -mtune=${model}\""
            echo "XUANTIE_MABI = \"${wo_mabi}\""
            echo "MACHINE = \"${wo_machine}\""
            echo "PACKAGE_EXTRA_ARCHS += \"${model} ${model}_external\""
        } > "$wo_distro_file"
        var_distro=$((var_distro + 1))
        # Dedicated machine conf for this variant
        if [[ "$model" == *-rv32 ]] || [[ "$model" == *-rv64 ]]; then
            : > "$MACHINE_DIR/${wo_distro_name}-tcxt.conf"
        else
            : > "$MACHINE_DIR/${wo_distro_name}-rv64-tcxt.conf"
        fi
        var_machine=$((var_machine + 1))
    fi

done

echo "Variant configs: $var_distro distro, $var_machine machine"

