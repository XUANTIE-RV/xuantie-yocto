    read -r distro_name _base machine _rest <<< "$entry"
    echo "conf/distro/${distro_name}.conf" >> "$META_DIR/.gitignore.distro"
    echo "conf/machine/${machine}.conf" >> "$META_DIR/.gitignore.distro"
done

