echo "" >> "$META_DIR/.gitignore.distro"
echo "# Auto-generated custom DISTRO configs" >> "$META_DIR/.gitignore.distro"
echo "conf/distro/custom-rv64.conf" >> "$META_DIR/.gitignore.distro"
echo "conf/distro/custom-rv32.conf" >> "$META_DIR/.gitignore.distro"
echo "conf/distro/custom-rva23.conf" >> "$META_DIR/.gitignore.distro"
echo "conf/machine/custom-rv64-rv64-tcxt.conf" >> "$META_DIR/.gitignore.distro"
echo "conf/machine/custom-rv32-rv32-tcxt.conf" >> "$META_DIR/.gitignore.distro"
echo "conf/machine/custom-rva23-rv64-tcxt.conf" >> "$META_DIR/.gitignore.distro"

# Merge into .gitignore if not already present
GITIGNORE="$META_DIR/.gitignore"
if [ ! -f "$GITIGNORE" ] || ! grep -q 'gitignore.distro' "$GITIGNORE"; then
    {
        echo "# Auto-generated distro/machine configs (regenerated by gen-cpu-confs.sh)"
        echo "!conf/distro/include/"
        echo "include .gitignore.distro"
    } > "$GITIGNORE"
fi

echo "Updated .gitignore.distro ($(wc -l < $META_DIR/.gitignore.distro) entries)"

# --- Step 8: Remove stale auto-generated files ---
# Compare snapshot from start-of-run against the newly written ledger. Any path
# present in the snapshot but missing from the new ledger was generated last
# run, is no longer expected, and must be removed.
stale_removed=0
if [ -f "$PREV_GITIGNORE_SNAPSHOT" ]; then
    while IFS= read -r path; do
        [ -z "$path" ] && continue
        if [ -f "$META_DIR/$path" ]; then
            rm -f "$META_DIR/$path"
            stale_removed=$((stale_removed + 1))
            echo "  [clean] removed stale: $path"
        fi
    done < <(comm -23 \
        <(grep '^conf/' "$PREV_GITIGNORE_SNAPSHOT" | sort -u) \
        <(grep '^conf/' "$META_DIR/.gitignore.distro" | sort -u))
    rm -f "$PREV_GITIGNORE_SNAPSHOT"
fi
echo "Stale cleanup: $stale_removed file(s) removed"
